import assert from 'node:assert/strict';
import {serialPoll} from './livery-designer/app/serialPoll.ts';
const delay=ms=>new Promise(resolve=>setTimeout(resolve,ms));
let calls=0,release,signal;
const poll=serialPoll(async s=>{calls++;signal=s;await new Promise(resolve=>release=resolve)},10);
const first=poll.refresh();
assert.equal(poll.refresh(),first);
await delay(35);
assert.equal(calls,1,'Slow reads must not overlap periodic or manual refreshes');
release();await first;await delay(25);
assert.equal(calls,2,'Next poll starts only after completion');
poll.stop();assert(signal.aborted);release();await delay(25);
await poll.refresh();assert.equal(calls,2,'Stopped poll must not restart');
let aborted=false;
const canceled=serialPoll(s=>new Promise((_,reject)=>s.addEventListener('abort',()=>{aborted=true;reject(s.reason)},{once:true})),1);
const pending=canceled.refresh();await delay(1);canceled.stop();await pending;assert(aborted);
let failedCalls=0;
const failing=serialPoll(async()=>{failedCalls++;throw Error('offline')},10);
await assert.rejects(failing.refresh(),/offline/);await delay(25);failing.stop();
assert(failedCalls>=2,'Polling may recover after read failure without concurrent reads');
console.log('serialPoll: coalescing, no overlap, abort, stop and recovery passed');
